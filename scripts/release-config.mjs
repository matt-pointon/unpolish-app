// Shared release settings. `scripts/release.mjs` writes `site/release.js` from this;
// the website, package metadata and tests all read the same object.
//
// Human-edited input: release.config.json (`published`, `siteUrl`, `distUrl`).
// Package name, version and executable come from packages/unpolish/package.json.

export const REPO_URL = 'https://github.com/matt-pointon/unpolish-app';
export const GITHUB_HOME = `${REPO_URL}#readme`;
export const GITHUB_PACKAGE_README = `${REPO_URL}/blob/main/packages/unpolish/README.md`;
export const GITHUB_BUGS = `${REPO_URL}/issues`;
export const GITHUB_REPO_GIT = `git+${REPO_URL}.git`;

export function normalizeHttpsUrl(value, field) {
  if (value == null || value === '') return null;
  let u;
  try { u = new URL(value); } catch {
    throw new Error(`release.config.json: ${field} is not a URL: ${value}`);
  }
  if (u.protocol !== 'https:') {
    throw new Error(`release.config.json: ${field} must use https:// so testers can install from it.`);
  }
  return u.href;
}

export function withTrailingSlash(href) {
  if (!href) return null;
  return href.endsWith('/') ? href : `${href}/`;
}

export function loadReleaseSettings(raw) {
  return {
    published: raw.published === true,
    siteUrl: withTrailingSlash(normalizeHttpsUrl(raw.siteUrl || raw.productionUrl, 'siteUrl')),
    distUrl: withTrailingSlash(normalizeHttpsUrl(raw.distUrl, 'distUrl')),
  };
}

export function executableName(pkg) {
  if (pkg.bin && typeof pkg.bin === 'object') {
    const keys = Object.keys(pkg.bin);
    if (keys.length) return keys[0];
  }
  return pkg.name;
}

function filesBase(settings) {
  if (settings.distUrl) return settings.distUrl;
  // siteUrl is the production website. Unpublished installs stay on the origin
  // serving the page (localhost in tests, *.vercel.app in production).
  if (settings.published && settings.siteUrl) return `${settings.siteUrl}unpolish/`;
  return null;
}

/** Build the object written to site/release.js. Pure: no I/O. */
export function buildRelease(pkg, settings) {
  const name = pkg.name;
  const version = pkg.version;
  const executable = executableName(pkg);
  const node = (pkg.engines && pkg.engines.node) || null;
  const published = settings.published === true;
  const siteUrl = settings.siteUrl || null;
  const distUrl = settings.distUrl || null;
  const tarball = `${name}-${version}.tgz`;
  const base = filesBase(settings);
  const homepage = siteUrl ? siteUrl.replace(/\/$/, '') : GITHUB_HOME;
  // Published mode must never fall back to the page origin — that would put
  // localhost into the copied prompt when previewing the site locally.
  const docsUrl = base ? `${base}README.md` : (published ? GITHUB_PACKAGE_README : null);
  const bundleUrl = base ? `${base}unpolish.js` : null;
  const schemaUrl = base ? `${base}unpolish.config.schema.json` : null;
  const configUrl = base ? `${base}unpolish.config.json` : null;
  const tarballUrl = (!published && base) ? `${base}${tarball}` : null;

  return {
    name,
    version,
    executable,
    node,
    published,
    siteUrl,
    distUrl,
    homepage,
    tarball,
    bundleUrl,
    docsUrl,
    schemaUrl,
    configUrl,
    tarballUrl,
    bundlePath: 'unpolish/unpolish.js',
    docsPath: 'unpolish/README.md',
    schemaPath: 'unpolish/unpolish.config.schema.json',
    configPath: 'unpolish/unpolish.config.json',
    tarballPath: `unpolish/${tarball}`,
    versionedPath: `unpolish/${version}/`,
  };
}

export function renderReleaseJs(release) {
  return (
    `// Generated by scripts/release.mjs — do not edit. The website builds its install commands from this.\n` +
    `window.UNPOLISH_RELEASE = ${JSON.stringify(release, null, 2)};\n`
  );
}

export function parseReleaseJs(src) {
  const start = src.indexOf('{');
  const end = src.lastIndexOf('}') + 1;
  return JSON.parse(src.slice(start, end));
}

export function packageMetadata(release) {
  return {
    repository: { type: 'git', url: GITHUB_REPO_GIT },
    homepage: release.homepage,
    bugs: { url: GITHUB_BUGS },
  };
}
