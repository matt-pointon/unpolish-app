// Prepares the release artifacts locally. Publishes and deploys nothing.
//
//   npm run release
//
// Distribution settings live in release.config.json (the only place to change them):
//   "published": false   the package is not on npm; installs use the packed tarball
//   "published": true    after `npm publish`; installs use `npx <name>@latest`
//   "distUrl": null      the tarball is served next to the website (unpolish/ on the same origin)
//   "distUrl": "https://…/unpolish/"   a public HTTPS folder holding the tarball and self-host files
//
// 1. Builds packages/unpolish (dist/).
// 2. Copies the self-host files into unpolish/ (served by the website, or uploaded to distUrl).
// 3. Packs the npm tarball to unpolish/<name>-<version>.tgz.
// 4. Writes site/release.js — package name, version, Node requirement and distribution —
//    from which the website generates every command, download link and the agent prompt.
import { readFileSync, writeFileSync, copyFileSync, readdirSync, rmSync, renameSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkgDir = join(root, 'packages', 'unpolish');
const out = join(root, 'unpolish');
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const settings = JSON.parse(readFileSync(join(root, 'release.config.json'), 'utf8'));
const published = settings.published === true;
let distUrl = settings.distUrl || null;
if (distUrl) {
  let u;
  try { u = new URL(distUrl); } catch { throw new Error(`release.config.json: distUrl is not a URL: ${distUrl}`); }
  if (u.protocol !== 'https:') throw new Error('release.config.json: distUrl must use https:// so testers can install from it.');
  distUrl = u.href.endsWith('/') ? u.href : u.href + '/';
}
const node = (pkg.engines && pkg.engines.node) || null;

execFileSync('node', ['scripts/build.mjs'], { cwd: pkgDir, stdio: 'inherit' });

copyFileSync(join(pkgDir, 'dist', 'unpolish.js'), join(out, 'unpolish.js'));
copyFileSync(join(pkgDir, 'schema', 'unpolish.config.schema.json'), join(out, 'unpolish.config.schema.json'));
copyFileSync(join(pkgDir, 'README.md'), join(out, 'README.md'));
const starter = JSON.parse(readFileSync(join(pkgDir, 'templates', 'unpolish.config.json'), 'utf8'));
writeFileSync(join(out, 'unpolish.config.json'), JSON.stringify({ $schema: './unpolish/unpolish.config.schema.json', ...starter }, null, 2) + '\n');

for (const f of readdirSync(out)) if (/^unpolish-.*\.tgz$/.test(f)) rmSync(join(out, f));
const tgz = execFileSync('npm', ['pack', '--silent', '--pack-destination', out], { cwd: pkgDir, encoding: 'utf8' }).trim().split('\n').pop();
const tarball = `${pkg.name}-${pkg.version}.tgz`;
if (tgz !== tarball) renameSync(join(out, tgz), join(out, tarball));

const release = { name: pkg.name, version: pkg.version, node, published, tarball, distUrl };
writeFileSync(join(root, 'site', 'release.js'),
  `// Generated by scripts/release.mjs — do not edit. The website builds its install commands from this.\n` +
  `window.UNPOLISH_RELEASE = ${JSON.stringify(release, null, 2)};\n`);
console.log(`\n${pkg.name} ${pkg.version} — ${published ? 'installs from npm' : `installs from ${distUrl ? distUrl + tarball : `unpolish/${tarball} on the site's origin`}`}\n  unpolish/unpolish.js\n  unpolish/${tarball}\n  site/release.js${distUrl && !published ? `\nUpload the contents of unpolish/ to ${distUrl}, then run: npm run check:dist` : ''}`);
